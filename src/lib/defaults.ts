export const TEXT_DEFAULTS: Record<string, { en: string; ar: string }> = Object.fromEntries(
  ENTRIES.map(([k, en, ar]) => [k, { en, ar }]),
);
export const TEXT_KEYS = ENTRIES.map(([k]) => k);

export type TextOverrides = { en: Record<string, string>; ar: Record<string, string> };

export function translate(
  overrides: TextOverrides | undefined,
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = overrides?.[lang]?.[key];
  if (s === undefined || s === "") s = TEXT_DEFAULTS[key]?.[lang];
  if (s === undefined || s === "") s = TEXT_DEFAULTS[key]?.en ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
